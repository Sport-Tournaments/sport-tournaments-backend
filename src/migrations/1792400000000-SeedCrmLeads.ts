interface ResearchLead {
  type: 'TOURNAMENT' | 'ORGANIZER';
  name: string;
  startDate: string | null;
  location: string | null;
  organiser: string | null;
  contactEmail: string | null;
  contactPhone: string | null;
  website: string | null;
  sourceUrl: string | null;
  priority: 'LOW' | 'MEDIUM' | 'HIGH';
  tags: string[];
  notes: string | null;
}

const blank = (v: string): string | null => (v.trim() ? v.trim() : null);

/** Map one research row to a lead; exported for tests. */
export function toResearchLead(row: ResearchRow): ResearchLead {
  const [name, kind, dateInfo, timing, city, county, age, organizer] = row;
  const [phone, email, website, source, notes] = row.slice(8);

  // "2026-07-23 to 2026-08-23" / "starts 2026-07-31" → first ISO date.
  const startDate = /(\d{4}-\d{2}-\d{2})/.exec(dateInfo)?.[1] ?? null;

  const emails = email
    .split(';')
    .map((e) => e.trim())
    .filter(Boolean);
  const sources = source
    .split(';')
    .map((s) => s.trim())
    .filter(Boolean);
  const firstUrl = sources.find((s) => /^https?:\/\//i.test(s)) ?? null;
  const otherSources = sources.filter((s) => s !== firstUrl);

  const isTournament = kind === 'tournament';
  const place = [
    blank(city),
    county.trim() && county.trim() !== city.trim()
      ? `jud. ${county.trim()}`
      : null,
  ]
    .filter(Boolean)
    .join(', ');

  const notesLines = [
    blank(notes),
    dateInfo.trim() && !startDate ? `Date: ${dateInfo.trim()}` : null,
    dateInfo.trim() && startDate && dateInfo.trim() !== startDate
      ? `Dates: ${dateInfo.trim()}`
      : null,
    blank(age) ? `Age category: ${age.trim()}` : null,
    emails.length > 1 ? `Other emails: ${emails.slice(1).join(', ')}` : null,
    otherSources.length ? `Sources: ${otherSources.join('; ')}` : null,
  ].filter(Boolean);

  return {
    type: isTournament ? 'TOURNAMENT' : 'ORGANIZER',
    name: name.trim(),
    startDate,
    location: place || null,
    organiser: blank(organizer),
    contactEmail: emails[0] ?? null,
    contactPhone: blank(phone),
    website: blank(website),
    sourceUrl: firstUrl,
    // Upcoming tournaments are the warmest outreach targets.
    priority: isTournament
      ? timing === 'upcoming'
        ? 'HIGH'
        : 'MEDIUM'
      : 'LOW',
    tags: [
      'romania',
      kind.replace(/_/g, '-'),
      ...(timing && timing !== 'unknown' ? [timing] : []),
    ],
    notes: notesLines.length ? notesLines.join('\n') : null,
  };
}

